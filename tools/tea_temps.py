"""270 / 350 K single-chain set, plus the no-TEA controls for the 280/350 K runs.

    .venv/bin/python tools/tea_temps.py plan
    .venv/bin/python tools/tea_temps.py init
    .venv/bin/python tools/tea_temps.py submit --yes --group controls

58 runs, all single free chains:

  4   controls      350 K, TEA OFF, the four sequences of the 280/350 K set.
                    Isolates lambda(T) from kT: these differ from
                    tea-*-free-350k in exactly one thing, so if the LCST
                    collapse is the stickiness and not the thermostat, these
                    stay expanded.
  2   vpgig         (VPGIG)71 + VP, 500 ns, 270 and 350 K. Bare ELP baseline.
  2   orig          the 357-aa original RGD construct, 270 and 350 K.
  2   allterm       every RGD block and lysine at the termini, 270 and 350 K.
  48  rgdarr01..24  the 24 arrangements again, 270 and 350 K.

270 K is EXTRAPOLATION
----------------------
TEA's hydration fits run 280-380 K. 270 K is 10 K below that and below the
freezing point of bulk water, so no data constrains lambda there. The numbers
are a smooth continuation of eq 2, not a prediction: lambda(I) 0.3618 -> 0.2546,
lambda(V) 0.1112 -> 0.0549, no sign flips. Every run asks for this in writing
via allow_extrapolation and records it in runtime/tea.yaml, and tools/tea.py
still refuses by default so no ordinary run can drift out there by accident.

Box
---
80 nm, up from the 60 nm of the 280/350 K set. At 280 K the chain already used
32 nm of extent and 2.1% of frames came within the cutoff of its own image; 270 K
is more expanded still. Both legs share the box so it is not a variable. The
controls stay at 60 nm, because a control must differ from what it controls in
one thing only.
"""

