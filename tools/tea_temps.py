def _sequence_of(sim_name: str, root: Path) -> str:
    """The sequence a prepared run uses, from its fasta if it has one."""
    fasta = root / "simulations" / sim_name / "runtime" / "molecules.fasta"
    if fasta.is_file():
        return "".join(fasta.read_text().splitlines()[1:]).strip()
    text = (root / "simulations" / sim_name / "prepare.py").read_text()
    seq = re.search(r'"([ACDEFGHIKLMNPQRSTVWYZ]{50,})"', text).group(1)
    return seq[1:] if seq.startswith("Z") else seq


def arrangements(root: Path) -> list[tuple[str, str]]:
    """(short label, source run) for the 24 free RGD arrangements, in order."""
    out = []
    for path in sorted((root / "simulations").glob("free-rgdarr*")):
        if path.name.endswith("-500ns"):
            continue            # a longer rerun of a sequence already in the set
        out.append((path.name.replace("free-rgdarr", "rgd"), path.name))
    if len(out) != 24:
        raise ValueError(f"expected 24 arrangements, found {len(out)}")
    return out


def cells(root: Path) -> list[dict]:
    out = []

    for i, (label, source) in enumerate(sorted(CONTROL_SOURCES.items())):
        out.append({
            "group": "controls", "name": f"ctrl-{label}-free-350k-notea",
            "title": f"No-TEA control for tea-{label}-free-350k.",
            "source": source, "tea": False, "extrapolate": False,
            "temperature": CONTROL_T, "ns": CONTROL_NS, "box": CONTROL_BOX_NM,
            "seed": _seed_of(source, root),
        })

    designed = [
        ("vpgig", "Bare ELP baseline: (VPGIG)71 + VP, no RGD and no lysine.",
         vpgig_only(root), NS_VPGIG),
        ("orig", "The 357-aa original RGD construct, verbatim.",
         original(root), NS_DEFAULT),
        ("allterm", "Original composition, every RGD block and lysine at the termini.",
         all_terminal(root), NS_DEFAULT),
    ]
    for i, (label, title, sequence, ns) in enumerate(designed):
        for j, T in enumerate(TEMPERATURES):
            out.append({
                "group": "designed", "name": f"tt-{label}-{int(T)}k", "title": title,
                "sequence": sequence, "tea": True, "extrapolate": True,
                "temperature": T, "ns": ns, "box": BOX_NM,
                "seed": SEED0 + 200 + i * 10 + j,
            })

    for i, (label, source) in enumerate(arrangements(root)):
        for j, T in enumerate(TEMPERATURES):
            out.append({
                "group": "arrangements", "name": f"tt-{label}-{int(T)}k",
                "title": f"RGD arrangement {label}, sequence from {source}.",
                "source": source, "tea": True, "extrapolate": True,
                "temperature": T, "ns": NS_DEFAULT, "box": BOX_NM,
                "seed": SEED0 + 1000 + i * 10 + j,
            })
    return out


def init(root: Path, groups: list[str] | None = None) -> list[dict]:
    made = [c for c in cells(root) if not groups or c["group"] in groups]
    for cell in made:
        sequence = cell.get("sequence") or _sequence_of(cell["source"], root)
        n_frames = int(round(cell["ns"] * 1000.0 / (N_SAVE * 0.01)))
        sim_dir = root / "simulations" / cell["name"]
        sim_dir.mkdir(parents=True, exist_ok=True)
        tea_line = (f"CALVADOS-TEA on, gamma {GAMMA:g}"
                    + (" — EXTRAPOLATED below the 280 K fit bound."
                       if cell["extrapolate"] and cell["temperature"] < 280.0 else ".")
                    ) if cell["tea"] else "TEA off (stock CALVADOS 2 lambda)."
        (sim_dir / "prepare.py").write_text(PREPARE.format(
            title=cell["title"], sequence=sequence, temperature=cell["temperature"],
            gamma=GAMMA, tea=cell["tea"], extrapolate=cell["extrapolate"],
            box=cell["box"], n_save=N_SAVE, n_frames=n_frames, seed=cell["seed"],
            ns=cell["ns"], tea_line=tea_line, partition=PARTITION,
            walltime=WALLTIME_500 if cell["ns"] > 400 else WALLTIME_300, cpus=CPUS))
        cell["n_residues"] = len(sequence)
        cell["n_frames"] = n_frames
    return made


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=["plan", "init", "submit", "status"])
    parser.add_argument("--group", action="append",
                        choices=["controls", "designed", "arrangements"],
                        help="limit to these groups (default: all)")
    parser.add_argument("--yes", action="store_true")
    args = parser.parse_args(argv)
    root = _project_root()
    made = [c for c in cells(root) if not args.group or c["group"] in args.group]

    if args.command in ("plan", "status"):
        print(f"{len(made)} runs, all single free chains")
        for cell in made:
            state = ""
            if args.command == "status":
                job = root / "simulations" / cell["name"] / "runtime" / "job.sh"
                state = "prepared" if job.is_file() else "not prepared"
            tea = f"TEA {GAMMA:g}" + ("*" if cell["extrapolate"]
                                      and cell["temperature"] < 280.0 else "") \
                if cell["tea"] else "no TEA"
            print(f"  {cell['name']:<32}{cell['group']:<14}{cell['temperature']:>5.0f} K"
                  f"{cell['ns']:>7.0f} ns  {cell['box']:>4.0f} nm  {tea:<9}{state}")
        if args.command == "plan":
            print("\n* = lambda extrapolated below TEA's 280 K fit bound")
            hours = sum(c["ns"] / 969.0 for c in made)
            print(f"measured 969-1174 ns/h -> ~{hours:.1f} GPU-hours of actual compute")
        return 0

    if args.command == "init":
        made = init(root, args.group)
        print(f"prepared {len(made)} runs")
        return 0

    missing = [c["name"] for c in made
               if not (root / "simulations" / c["name"] / "runtime" / "job.sh").is_file()]
    if missing:
        print(f"{len(missing)} run(s) have no runtime/job.sh — `init` then `sim prepare`:")
        for name in missing[:6]:
            print(f"  {name}")
        return 1
    if not args.yes:
        print(f"would sbatch {len(made)} jobs; re-run with --yes")
        return 0
    for cell in made:
        subprocess.run(["sbatch", str(root / "simulations" / cell["name"]
                                      / "runtime" / "job.sh")], cwd=root, check=False)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
