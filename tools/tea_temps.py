def _seed_of(sim_name: str, root: Path) -> int:
    """The seed a prepared run used, from its own config.yaml."""
    config = root / "simulations" / sim_name / "runtime" / "config.yaml"
    for line in config.read_text().splitlines():
        if line.strip().startswith("random_number_seed:"):
            return int(line.split(":", 1)[1])
    raise ValueError(f"no random_number_seed in {config}")

